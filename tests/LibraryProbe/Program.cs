using System.Reflection;
using System.Runtime.CompilerServices;
using Ludex;
using Ludex.Services;
using Ludex.UI;

// Exercise library operations without displaying a window or touching a real profile.
string temp = Path.Combine(Path.GetTempPath(), "ludex-library-probe-" + Guid.NewGuid().ToString("N"));
Directory.CreateDirectory(temp);
Environment.SetEnvironmentVariable("XDG_DATA_HOME", Path.Combine(temp, "data"));
int count = 0;
void Check(bool condition, string message) { count++; if (!condition) throw new Exception("FAIL " + message); Console.WriteLine("PASS " + message); }
try
{
    var window = (MainWindow)RuntimeHelpers.GetUninitializedObject(typeof(MainWindow));
    var games = new List<GameEntry>();
    const BindingFlags flags = BindingFlags.NonPublic | BindingFlags.Instance;
    typeof(MainWindow).GetField("_games", flags)!.SetValue(window, games);
    typeof(MainWindow).GetField("_settings", flags)!.SetValue(window, new AppSettings());
    object Call(string method, params object[] args) => typeof(MainWindow).GetMethod(method, flags)!.Invoke(window, args)!;
    var offline = new GameEntry { Title = "Offline", FolderPath = Path.Combine(temp, "offline"), ExePath = Path.Combine(temp, "offline", "game.exe"), Source = "steam", FromLauncher = true, Favorite = true, PlayCount = 42 };
    games.Add(offline);
    Call("MergeHits", new List<ScanHit>());
    Check(games.Contains(offline) && offline.Favorite && offline.PlayCount == 42, "empty scan preserves inaccessible game and metadata");
    Call("MergeImported", new List<LauncherGame>());
    Check(games.Contains(offline) && offline.Source == "steam" && offline.FromLauncher, "empty launcher import preserves inaccessible game and source");
    string first = Path.Combine(temp, "disk1", "Portal 2"), second = Path.Combine(temp, "disk2", "Portal 2");
    Directory.CreateDirectory(first); Directory.CreateDirectory(second);
    var one = new GameEntry { Title = "Portal 2", FolderPath = first, ExePath = Path.Combine(first, "game.exe") };
    var two = new GameEntry { Title = "Portal 2", FolderPath = second, ExePath = Path.Combine(second, "game.exe") };
    var duplicate = new GameEntry { Title = "Other name", FolderPath = first + Path.DirectorySeparatorChar, ExePath = one.ExePath, Favorite = true, PlayCount = 12 };
    var sameFolderDifferentExe = new GameEntry { Title = "Another game", FolderPath = first, ExePath = Path.Combine(first, "another.exe") };
    var missingExe = new GameEntry { Title = "Unknown executable", FolderPath = first, ExePath = "" };
    games.AddRange(new[] { one, two, duplicate, sameFolderDifferentExe, missingExe });
    Call("RemoveDuplicates");
    Check(games.Contains(one) && games.Contains(two), "same title on separate disks remains separate");
    Check(games.Contains(sameFolderDifferentExe) && games.Contains(missingExe), "different or unknown executables in same folder are not merged");
    Check(!games.Contains(duplicate) && one.Favorite && one.PlayCount == 12, "same folder and executable deduplicate and preserve metadata");
    var third = Path.Combine(temp, "disk3", "Portal 2");
    Call("MergeImported", new List<LauncherGame> { new() { Title = "Portal 2", Folder = third, Exe = Path.Combine(third, "game.exe"), Launcher = "steam", AppId = 620 } });
    Check(games.Any(g => g.FolderPath == third && g.Source == "steam") && games.Contains(one) && games.Contains(two), "import of same title on another disk creates separate entry");
    Check(games.Contains(offline), "partial import does not remove earlier launcher entries");
    games.Clear();
    string root = Path.Combine(temp, "SteamLibrary", "steamapps", "common", "Deep Rock Galactic");
    string nested = Path.Combine(root, "FSD", "Binaries", "Win64");
    Directory.CreateDirectory(nested);
    string rootExe = Path.Combine(root, "FSD.exe"), nestedExe = Path.Combine(nested, "FSD-Win64-Shipping.exe");
    File.WriteAllText(rootExe, "test launcher");
    using (var sparse = new FileStream(nestedExe, FileMode.Create, FileAccess.Write)) sparse.SetLength(157286400);
    Directory.CreateDirectory(Path.Combine(root, "FSD", "Content"));
    var detectGame = typeof(AutoScanner).GetMethod("DetectGame", BindingFlags.NonPublic | BindingFlags.Static)!;
    var detected = (AutoScanner.Hit?)detectGame.Invoke(null, new object[] { new DirectoryInfo(nested), "steam" });
    Check(detected != null && detected.Folder == nested && detected.Exe == nestedExe && detected.Title == "Deep Rock Galactic", "real auto scanner detects Unreal nested EXE and identifies root game");
    var steamRoot = new GameEntry { Title = "Deep Rock Galactic", FolderPath = root, ExePath = rootExe, Source = "steam", FromLauncher = true, SteamAppId = 548430, PlayCount = 3 };
    var nestedCard = new GameEntry { Title = "Deep Rock Galactic", FolderPath = nested, ExePath = nestedExe, Source = "steam", Favorite = true, PlayCount = 7 };
    games.AddRange(new[] { steamRoot, nestedCard });
    Call("RemoveDuplicates");
    Check(games.Count == 1 && games.Contains(steamRoot) && steamRoot.ExePath == rootExe && steamRoot.Favorite && steamRoot.PlayCount == 7, "existing Unreal child card is merged safely into Steam installation");
    var backup = Directory.GetFiles(AppPaths.Root, "library.before-unreal-merge-*.json").OrderByDescending(File.GetLastWriteTimeUtc).FirstOrDefault();
    using (var saved = System.Text.Json.JsonDocument.Parse(File.ReadAllText(backup ?? throw new Exception("Backup missing"))))
        Check(saved.RootElement.GetProperty("Games").GetArrayLength() == 2, "backup contains both cards before automatic merge");
    Call("MergeHits", new List<ScanHit> { new() { Title = detected!.Title, FolderPath = detected.Folder, ExePath = detected.Exe } });
    Check(games.Count == 1 && steamRoot.ExePath == rootExe, "real auto scanner hit does not recreate nested Unreal executable");
    Call("MergeHits", new List<ScanHit> { new() { Title = "Deep Rock Galactic", FolderPath = root, ExePath = nestedExe } });
    Check(games.Count == 1 && steamRoot.ExePath == rootExe, "scan does not replace original Steam launcher by nested executable");
    Call("MergeHits", new List<ScanHit> { new() { Title = "FSD", FolderPath = nested, ExePath = nestedExe } });
    Check(games.Count == 1 && steamRoot.ExePath == rootExe, "raw Unreal project title does not recreate nested card");
    Call("MergeHits", new List<ScanHit> { new() { Title = "FSD", FolderPath = Path.Combine(root, "FSD"), ExePath = nestedExe } });
    Check(games.Count == 1 && steamRoot.ExePath == rootExe, "scan hit attributed to project folder does not create duplicate");
    Call("MergeHits", new List<ScanHit> { new() { Title = "FSD Win64 Shipping", FolderPath = Path.Combine(root, "FSD", "Binaries"), ExePath = nestedExe } });
    Check(games.Count == 1 && steamRoot.ExePath == rootExe, "scan hit attributed to binaries folder does not create duplicate");
    games.Clear();
    games.Add(new GameEntry { Title = "Deep Rock Galactic", FolderPath = nested, ExePath = nestedExe, Favorite = true });
    Call("MergeImported", new List<LauncherGame> { new() { Title = "Deep Rock Galactic", Folder = root, Exe = rootExe, Launcher = "steam", AppId = 548430 } });
    Call("RemoveDuplicates");
    Check(games.Count == 1 && games[0].FolderPath == root && games[0].Favorite, "Steam import after scanning merges exact Unreal child into root");
    games.Clear();
    games.Add(new GameEntry { Title = "FSD", FolderPath = nested, ExePath = nestedExe });
    Call("MergeImported", new List<LauncherGame> { new() { Title = "Deep Rock Galactic", Folder = root, Exe = rootExe, Launcher = "steam", AppId = 548430 } });
    Call("RemoveDuplicates");
    Check(games.Count == 1 && games[0].FolderPath == root, "raw uncustomized project hit merges when Steam import follows scan");
    games.Clear();
    games.Add(new GameEntry { Title = "FSD Win64 Shipping", FolderPath = Path.Combine(root, "FSD", "Binaries"), ExePath = nestedExe });
    Call("MergeImported", new List<LauncherGame> { new() { Title = "Deep Rock Galactic", Folder = root, Exe = rootExe, Launcher = "steam", AppId = 548430 } });
    Call("RemoveDuplicates");
    Check(games.Count == 1 && games[0].FolderPath == root, "existing scan duplicate attributed to Binaries is merged into Steam root");
    games.Clear();
    var parent = new GameEntry { Title = "Deep Rock Galactic", FolderPath = root, ExePath = rootExe, Source = "steam", SteamAppId = 548430 };
    var otherId = new GameEntry { Title = "Deep Rock Galactic", FolderPath = nested, ExePath = nestedExe, Source = "steam", SteamAppId = 999999 };
    games.AddRange(new[] { parent, otherId });
    Call("RemoveDuplicates");
    Check(games.Count == 2, "nested entry with different Steam identity is not merged");
    games.Clear(); games.Add(parent);
    var differentTitle = new GameEntry { Title = "Different Game", FolderPath = nested, ExePath = nestedExe };
    games.Add(differentTitle); Call("RemoveDuplicates");
    Check(games.Count == 2, "different title is not merged merely because path is nested");
    games.Clear(); games.Add(parent);
    var customizedProject = new GameEntry { Title = "FSD", FolderPath = nested, ExePath = nestedExe, Favorite = true };
    games.Add(customizedProject); Call("RemoveDuplicates");
    Check(games.Count == 2, "customized entry with project-only name is not deleted without matching title or ID");
    games.Clear(); games.Add(parent);
    var backupFailureCard = new GameEntry { Title = "Deep Rock Galactic", FolderPath = nested, ExePath = nestedExe };
    games.Add(backupFailureCard);
    var rootField = typeof(AppPaths).GetField("_root", BindingFlags.NonPublic | BindingFlags.Static)!;
    var oldAppRoot = rootField.GetValue(null);
    string unusableRoot = Path.Combine(temp, "not-a-directory"); File.WriteAllText(unusableRoot, "file");
    rootField.SetValue(null, unusableRoot);
    try { Call("RemoveDuplicates"); }
    finally { rootField.SetValue(null, oldAppRoot); }
    Check(games.Count == 2, "backup failure prevents automatic removal");
    games.Clear(); games.Add(parent);
    var nestedMissing = new GameEntry { Title = "Deep Rock Galactic", FolderPath = nested, ExePath = nestedExe };
    games.Add(nestedMissing); File.Delete(nestedExe); Call("RemoveDuplicates");
    Check(games.Count == 2, "inaccessible executable does not cause automatic deletion");
    Console.WriteLine($"{count} checks passed");
}
finally { try { Directory.Delete(temp, true); } catch { } }
